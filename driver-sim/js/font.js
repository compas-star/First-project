export function textWidth(str, s = 1) {
  let w = 0;
  for (const ch of str.toUpperCase()) { const g = G[ch] || G['?']; w += (g[0].length + 1) * s; }
  return Math.max(0, w - s);
}

export function drawText(ctx, str, x, y, color, s = 1, align = 'left', shadow) {
  str = String(str).toUpperCase();
  let cx = Math.round(align === 'center' ? x - textWidth(str, s) / 2 : align === 'right' ? x - textWidth(str, s) : x);
  y = Math.round(y);
  if (shadow) drawText(ctx, str, cx + s, y + s, shadow, s, 'left');
  ctx.fillStyle = color;
  for (const ch of str) {
    const g = G[ch] || G['?'];
    for (let r = 0; r < 5; r++) for (let c = 0; c < g[r].length; c++)
      if (g[r][c] === '1') ctx.fillRect(cx + c * s, y + r * s, s, s);
    cx += (g[0].length + 1) * s;
  }
}
